  @spec names() :: [binary]
  def names, do: @palettes |> Map.keys() |> Enum.sort()

  @doc "Palette for a name or alias (case, space and underscore insensitive); unknown names give catppuccin."
  @spec get(term) :: %{atom => term}
  def get(name) do
    key = if is_binary(name), do: name |> String.downcase() |> String.replace([" ", "_"], "-")
    Map.get(@palettes, Map.get(@aliases, key, key)) || Map.fetch!(@palettes, "catppuccin")
  end
